export const LESSON_BY_ID: Record<string, Lesson> = {};
for (const lesson of LESSONS) LESSON_BY_ID[lesson.id] = lesson;

export function getLesson(id: string | undefined): Lesson | undefined {
  if (!id) return undefined;
  return LESSON_BY_ID[id];
}

export function categoryLabel(id: LessonCategoryId): string {
  return LESSON_CATEGORIES.find((category) => category.id === id)?.label ?? id;
}

export function categoryColor(id: LessonCategoryId): string {
  return LESSON_CATEGORIES.find((category) => category.id === id)?.color ?? '#C9F26B';
}
